/**
 * Input elements have the notion of status which we can read or modify
 * 
 * For text inputs that notion is the text, for checkbox it is whether the box checked. For radio button, it is option which is selected
 * 
 * for input elements following are prevalent 
 * - **`el.value`** is the current value of the input.
- **`el.focus()`** gives the element keyboard focus, so the next key the user presses goes into it.
- **`el.select()`** selects all the contents of the input.
- **`el.disabled`** controls whether the input is disabled.
- **`el.checked`** is whether a checkbox or radio button is on.
 */